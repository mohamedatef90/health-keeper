        .where((meal) => meal.calories >= min && meal.calories <= max)
        .toList();
  }

  /// Get meals with minimum protein
  static List<EgyptianMeal> getMealsWithMinProtein(int minProtein) {
    return meals.where((meal) => meal.protein >= minProtein).toList();
  }
