      meals.where((meal) => meal.isLowCarb).toList();

  /// Search meals by name (Arabic or English)
  static List<EgyptianMeal> searchMeals(String query) {
    final lowerQuery = query.toLowerCase();
    return meals
        .where((meal) =>
            meal.name.contains(query) ||
            meal.nameEn.toLowerCase().contains(lowerQuery))
        .toList();
  }

