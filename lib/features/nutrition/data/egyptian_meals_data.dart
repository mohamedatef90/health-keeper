/// Egyptian meals database for AI-powered diet suggestions
///
/// Contains traditional Egyptian dishes with nutritional estimates.
/// All calorie and macro values are estimates based on standard portion sizes.
///
/// Categories: breakfast, lunch, dinner, snack
/// All meals include both Arabic and English names for localization.
library;

/// Egyptian meal data with nutritional information
class EgyptianMeal {
  final String name;
  final String nameEn;
  final int calories;
  final int protein;
  final int carbs;
  final int fat;
  final String category;
  final String? servingSize;
  final List<String> tags;
  final bool isHighProtein;
  final bool isVegetarian;
  final bool isLowCarb;

  const EgyptianMeal({
    required this.name,
    required this.nameEn,
    required this.calories,
    required this.protein,
    required this.carbs,
    required this.fat,
    required this.category,
    this.servingSize,
    this.tags = const [],
    this.isHighProtein = false,
    this.isVegetarian = false,
    this.isLowCarb = false,
  });

  Map<String, dynamic> toJson() => {
        'name': name,
        'nameEn': nameEn,
        'calories': calories,
        'protein': protein,
        'carbs': carbs,
        'fat': fat,
        'category': category,
        'servingSize': servingSize,
        'tags': tags,
        'isHighProtein': isHighProtein,
        'isVegetarian': isVegetarian,
        'isLowCarb': isLowCarb,
      };

  factory EgyptianMeal.fromJson(Map<String, dynamic> json) => EgyptianMeal(
        name: json['name'] as String,
        nameEn: json['nameEn'] as String,
        calories: json['calories'] as int,
        protein: json['protein'] as int,
        carbs: json['carbs'] as int,
        fat: json['fat'] as int,
        category: json['category'] as String,
        servingSize: json['servingSize'] as String?,
        tags: (json['tags'] as List?)?.cast<String>() ?? [],
        isHighProtein: json['isHighProtein'] as bool? ?? false,
        isVegetarian: json['isVegetarian'] as bool? ?? false,
        isLowCarb: json['isLowCarb'] as bool? ?? false,
      );
}

