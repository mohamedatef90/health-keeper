/// Approval status for interconnected plans
enum PlanApprovalStatus {
  pending('pending'),
  approved('approved'),
  rejected('rejected'),
  modified('modified');

  final String value;
  const PlanApprovalStatus(this.value);

  static PlanApprovalStatus fromString(String value) {
    return PlanApprovalStatus.values.firstWhere(
      (e) => e.value == value,
      orElse: () => PlanApprovalStatus.pending,
    );
  }
}

/// A complete 7-day meal plan generated by AI
@freezed
class WeeklyMealPlan with _$WeeklyMealPlan {
  const WeeklyMealPlan._();

  const factory WeeklyMealPlan({
    required String id,

    /// Start date of the week (Monday)
    required DateTime weekStartDate,

    /// When this plan was generated
    required DateTime generatedAt,

    /// Daily meal plans for each day of the week
    DailyMealPlan? monday,
    DailyMealPlan? tuesday,
    DailyMealPlan? wednesday,
    DailyMealPlan? thursday,
    DailyMealPlan? friday,
    DailyMealPlan? saturday,
    DailyMealPlan? sunday,

    /// Weekly calorie target
    @Default(14000) int weeklyCalorieTarget,

    /// Weekly protein target in grams
    @Default(840) int weeklyProteinTarget,

    /// Total planned calories for the week
    @Default(0) int totalCalories,

    /// Total planned protein for the week
    @Default(0) int totalProtein,

    /// Total planned carbs for the week
    @Default(0) int totalCarbs,

    /// Total planned fat for the week
    @Default(0) int totalFat,

    /// Recovery score at the time of generation
    int? recoveryScoreAtGeneration,

    /// Strain score at the time of generation
    double? strainScoreAtGeneration,

    /// Is this an AI-generated plan?
    @Default(true) bool isAiGenerated,

    /// AI coaching note about the weekly plan
    String? coachingNote,

    /// Arabic coaching note
    String? coachingNoteAr,

    /// User's approval status
    @Default(PlanApprovalStatus.pending) PlanApprovalStatus approvalStatus,

    /// Linked workout plan ID for interconnection
    String? linkedWorkoutPlanId,

    /// Whether this plan was adjusted based on workout plan
    @Default(false) bool adjustedForWorkouts,

    /// Days with workouts (for highlighting)
    @Default([]) List<int> workoutDays,

    /// Dietary restrictions considered
    @Default([]) List<String> dietaryRestrictions,

    /// Cuisine preferences
    @Default(['egyptian']) List<String> cuisinePreferences,
  }) = _WeeklyMealPlan;

  factory WeeklyMealPlan.fromJson(Map<String, dynamic> json) =>
      _$WeeklyMealPlanFromJson(json);

  /// Get all daily plans as a list
  List<DailyMealPlan?> get dailyPlans => [
        monday,
        tuesday,
        wednesday,
        thursday,
        friday,
        saturday,
        sunday,
      ];

  /// Get daily plan by day index (0 = Monday, 6 = Sunday)
  DailyMealPlan? getDayPlan(int dayIndex) {
    switch (dayIndex) {
      case 0:
        return monday;
      case 1:
        return tuesday;
      case 2:
        return wednesday;
      case 3:
        return thursday;
      case 4:
        return friday;
      case 5:
        return saturday;
      case 6:
        return sunday;
      default:
        return null;
    }
  }

  /// Get day name by index
  static String getDayName(int dayIndex, {bool arabic = false}) {
    const englishDays = [
      'Monday',
      'Tuesday',
      'Wednesday',
      'Thursday',
      'Friday',
      'Saturday',
      'Sunday'
    ];
    const arabicDays = [
      'الإثنين',
      'الثلاثاء',
      'الأربعاء',
      'الخميس',
      'الجمعة',
      'السبت',
      'الأحد'
    ];
    if (dayIndex < 0 || dayIndex > 6) return '';
    return arabic ? arabicDays[dayIndex] : englishDays[dayIndex];
  }

  /// Count of days with meal plans
  int get plannedDaysCount =>
      dailyPlans.where((plan) => plan != null).length;

  /// Is the plan complete (all 7 days)?
  bool get isComplete => plannedDaysCount == 7;

  /// Average daily calories
  int get averageDailyCalories =>
      plannedDaysCount > 0 ? totalCalories ~/ plannedDaysCount : 0;

  /// Average daily protein
  int get averageDailyProtein =>
      plannedDaysCount > 0 ? totalProtein ~/ plannedDaysCount : 0;

  /// Calorie surplus/deficit for the week
  int get weeklyCalorieBalance => totalCalories - weeklyCalorieTarget;

  /// Protein surplus/deficit for the week
  int get weeklyProteinBalance => totalProtein - weeklyProteinTarget;

  /// Is meeting weekly calorie target (within 10%)?
  bool get meetsWeeklyCalorieTarget {
    final tolerance = weeklyCalorieTarget * 0.1;
    return weeklyCalorieBalance.abs() <= tolerance;
  }

  /// Is meeting weekly protein target (within 10%)?
  bool get meetsWeeklyProteinTarget {
    final tolerance = weeklyProteinTarget * 0.1;
    return weeklyProteinBalance.abs() <= tolerance;
  }

  /// Check if a specific day is a workout day
  bool isWorkoutDay(int dayIndex) => workoutDays.contains(dayIndex);

  /// Get the date for a specific day index
  DateTime getDateForDay(int dayIndex) =>
      weekStartDate.add(Duration(days: dayIndex));
}

