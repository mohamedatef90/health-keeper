/// Represents a pending change to a meal plan from workout coordination
@freezed
class MealPlanChange with _$MealPlanChange {
  const factory MealPlanChange({
    required String id,

    /// Day index affected (0 = Monday)
    required int dayIndex,

    /// Type of change
    required MealPlanChangeType changeType,

    /// Description in English
    required String description,

    /// Description in Arabic
    required String descriptionAr,

    /// What triggered this change
    required String trigger,

    /// Proposed new calorie target
    int? proposedCalories,

    /// Proposed new protein target
    int? proposedProtein,

    /// Original calorie target
    int? originalCalories,

    /// Original protein target
    int? originalProtein,

    /// Whether this change is approved
    @Default(false) bool isApproved,

    /// Whether this change is rejected
    @Default(false) bool isRejected,
  }) = _MealPlanChange;

  factory MealPlanChange.fromJson(Map<String, dynamic> json) =>
      _$MealPlanChangeFromJson(json);
}

/// Types of changes to meal plans
enum MealPlanChangeType {
  calorieIncrease('calorie_increase', 'زيادة السعرات'),
  calorieDecrease('calorie_decrease', 'تقليل السعرات'),
  proteinIncrease('protein_increase', 'زيادة البروتين'),
  proteinDecrease('protein_decrease', 'تقليل البروتين'),
  mealTiming('meal_timing', 'توقيت الوجبات'),
  restDayAdjustment('rest_day_adjustment', 'تعديل يوم الراحة');

  final String value;
  final String arabicName;
  const MealPlanChangeType(this.value, this.arabicName);

  static MealPlanChangeType fromString(String value) {
    return MealPlanChangeType.values.firstWhere(
      (e) => e.value == value,
      orElse: () => MealPlanChangeType.calorieIncrease,
    );
  }
}
