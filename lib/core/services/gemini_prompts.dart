/// Illness prediction prompt
///
/// Input: 7-day HRV trend, respiratory rate, sleep quality, symptoms
/// Output: Risk assessment (0-100%), contributing factors, recommendations
class IllnessPredictionPrompt {
  static String build({
    required List<int> hrvLast7Days,
    required int? baselineHrv,
    required List<double> respiratoryRateLast7Days,
    required List<double> sleepHoursLast7Days,
    required List<int> sleepQualityLast7Days,
    required List<int> rhrLast7Days,
    required int? baselineRhr,
    required List<double>? spo2Last7Days,
    required List<String> currentSymptoms,
    required int? moodEnergy,
    required int? stressLevel,
    String language = 'en',
  }) {
    final lang = language == 'ar' ? 'Arabic' : 'English';

    return '''
$aiSafetyPreamble

You are a health pattern analyst. Analyze the following biometric data to assess if there are patterns that may indicate the body is fighting off an illness or under unusual stress.

## INPUT DATA

### HRV (Heart Rate Variability) - Last 7 Days:
$hrvLast7Days
Baseline HRV: ${baselineHrv ?? 'Unknown'}
(Lower HRV compared to baseline may indicate immune response or stress)

### Resting Heart Rate - Last 7 Days:
$rhrLast7Days
Baseline RHR: ${baselineRhr ?? 'Unknown'}
(Elevated RHR can indicate the body is fighting infection)

### Sleep Data - Last 7 Days:
Hours: $sleepHoursLast7Days
Quality (0-100): $sleepQualityLast7Days
(Poor sleep can both indicate and contribute to illness)

### Respiratory Rate - Last 7 Days:
$respiratoryRateLast7Days
(Elevated respiratory rate can indicate respiratory issues)

### SpO2 (Blood Oxygen) - Last 7 Days:
${spo2Last7Days ?? 'Not available'}
(Low SpO2 may indicate respiratory concerns)

### Current Symptoms Reported:
${currentSymptoms.isEmpty ? 'None reported' : currentSymptoms.join(', ')}

### Subjective Data:
- Mood/Energy Level: ${moodEnergy ?? 'Not reported'}/5
- Stress Level: ${stressLevel ?? 'Not reported'}/5

## OUTPUT REQUIREMENTS

Respond in $lang with a JSON object in this exact format:

```json
{
  "probability": <0-100, percentage chance of developing illness in next 24-48 hours>,
  "riskLevel": "<low|moderate|elevated|high>",
  "confidence": <0-100, how confident you are in this assessment>,
  "contributingFactors": [
    {
      "factor": "<metric name>",
      "observation": "<what was observed>",
      "normalRange": "<what would be considered normal>",
      "impactScore": <0-100>,
      "trend": "<improving|stable|declining|rapidly_declining>"
    }
  ],
  "preventiveActions": [
    {
      "action": "<specific action to take>",
      "rationale": "<why this helps>",
      "priority": "<immediate|high|medium|low>",
      "category": "<sleep|nutrition|hydration|activity|stress|medical>"
    }
  ],
  "symptoms": ["<any inferred symptoms based on data>"],
  "timeframe": "<e.g., 'next 24-48 hours' or 'coming days'>",
  "explanation": "<2-3 sentence explanation of the assessment>",
  "shouldConsultDoctor": <true if symptoms warrant medical attention, false otherwise>
}
```

## ANALYSIS GUIDELINES

1. HRV Analysis:
   - Drop of 10-15% below baseline: Minor concern
   - Drop of 15-25% below baseline: Moderate concern
   - Drop of >25% below baseline: Significant concern
   - Look for consistent downward trends

2. RHR Analysis:
   - Elevation of 5-10 bpm above baseline: Minor concern
   - Elevation of 10-15 bpm: Moderate concern
   - Elevation of >15 bpm: Significant concern

3. Sleep Analysis:
   - Disrupted sleep patterns often precede illness
   - Look for quality drops combined with biometric changes

4. Pattern Recognition:
   - Multiple metrics declining together = higher concern
   - Single metric change = lower concern
   - User-reported symptoms + biometric changes = highest concern

5. Confidence Scoring:
   - More data points = higher confidence
   - Clear trends = higher confidence
   - Conflicting signals = lower confidence
   - Missing data = lower confidence

BE SUPPORTIVE, NOT ALARMIST. Focus on actionable prevention.
''';
  }
}

